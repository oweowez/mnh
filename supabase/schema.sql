create table if not exists professions (
  id integer generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  short_desc text not null default '',
  ordre integer not null default 0,
  visible integer not null default 1,
  archived integer not null default 0
);

create table if not exists themes (
  id integer generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  description text not null default '',
  ordre integer not null default 0,
  visible integer not null default 1
);

create table if not exists studies (
  id integer generated by default as identity primary key,
  slug text unique not null,
  ref_num integer,
  name text not null,
  full_title text not null default '',
  team text not null default '',
  type text not null default '',
  date_label text not null default '',
  resume text not null default '',
  url text not null default '',
  statut text not null default 'publie'
);

create table if not exists contents (
  id integer generated by default as identity primary key,
  profession_id integer not null references professions(id),
  theme_id integer not null references themes(id),
  ordre integer not null default 0,
  display_theme_label text not null default '',
  titre text not null default '',
  message_cle text not null default '',
  dev_court text not null default '',
  corps_web text not null default '',
  nuance text not null default '',
  decideur text not null default '',
  priorite text not null default '',
  statut text not null default 'publie',
  updated_at timestamptz not null default now()
);

create table if not exists content_refs (
  content_id integer not null references contents(id) on delete cascade,
  study_id integer not null references studies(id) on delete cascade,
  primary key (content_id, study_id)
);

create table if not exists study_professions (
  study_id integer not null references studies(id) on delete cascade,
  profession_id integer not null references professions(id) on delete cascade,
  primary key (study_id, profession_id)
);

create table if not exists study_themes (
  study_id integer not null references studies(id) on delete cascade,
  theme_id integer not null references themes(id) on delete cascade,
  primary key (study_id, theme_id)
);

create table if not exists pages (
  id integer generated by default as identity primary key,
  slug text unique not null,
  title text not null default '',
  body text not null default ''
);

create table if not exists publications (
  id integer generated by default as identity primary key,
  title text not null default '',
  source_type text not null default 'manuel',
  source_ref text not null default '',
  raw_text text not null default '',
  file_path text not null default '',
  statut text not null default 'nouvelle',
  analysis text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists proposals (
  id integer generated by default as identity primary key,
  publication_id integer not null references publications(id) on delete cascade,
  content_id integer references contents(id),
  profession_id integer references professions(id),
  theme_id integer references themes(id),
  kind text not null,
  titre text not null default '',
  current_text text not null default '',
  proposed_text text not null default '',
  rationale text not null default '',
  source_excerpt text not null default '',
  statut text not null default 'en_attente',
  decided_by text not null default '',
  decided_at text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists content_versions (
  id integer generated by default as identity primary key,
  content_id integer not null references contents(id) on delete cascade,
  snapshot text not null,
  reason text not null default '',
  changed_by text not null default '',
  publication_id integer,
  created_at timestamptz not null default now()
);

-- Vues de lecture (jointures pré-câblées pour l'application)
create or replace view v_contents_full with (security_invoker = true) as
select c.*,
       p.slug as profession_slug, p.name as profession_name, p.ordre as profession_ordre,
       p.visible as profession_visible, p.archived as profession_archived,
       t.slug as theme_slug, t.name as theme_name
from contents c
join professions p on p.id = c.profession_id
join themes t on t.id = c.theme_id;

create or replace view v_recent_versions with (security_invoker = true) as
select v.id, v.created_at, v.reason, v.changed_by, v.publication_id,
       c.id as content_id, c.titre,
       p.name as profession_name,
       coalesce(nullif(c.display_theme_label, ''), t.name) as theme_label
from content_versions v
join contents c on c.id = v.content_id
join professions p on p.id = c.profession_id
join themes t on t.id = c.theme_id;

