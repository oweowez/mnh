alter table content_refs enable row level security;
alter table study_professions enable row level security;
alter table study_themes enable row level security;
alter table pages enable row level security;
alter table publications enable row level security;
alter table proposals enable row level security;
alter table content_versions enable row level security;

-- Après une migration avec ids explicites : resynchronise les séquences.
create or replace function fix_sequences() returns void
language plpgsql security definer as $$
declare t text;
begin
  foreach t in array array['professions','themes','studies','contents','pages','publications','proposals','content_versions'] loop
    execute format(
      'select setval(pg_get_serial_sequence(%L, ''id''), coalesce((select max(id) from %I), 0) + 1, false)',
      t, t
    );
  end loop;
end $$;
